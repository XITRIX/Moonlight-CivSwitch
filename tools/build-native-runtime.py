#!/usr/bin/env python3
"""Bundle the pinned, reviewed console-only Moonlight-nx2 modules as classic JS.

This intentionally supports only the selected snapshot's simple module syntax.
It never includes the PC protocol helper, transport service, or launcher.
"""
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'third_party/moonlight-nx2'
OUT = ROOT / 'app/vendor/moonlight-nx2-runtime.js'
PUBLIC = {
    'bitrate': 'src/streamer/session/bitrate.js',
    'bitrateAdaptation': 'src/streamer/civ7/bitrate-adaptation.js',
    'display': 'src/streamer/civ7/display.js',
    'callPlan': 'src/streamer/civ7/call-plan.js',
    'pipelines': 'src/streamer/civ7/renderer-pipelines.js',
    'pipelineHelpers': 'src/streamer/civ7/pipelines.js',
    'presentation': 'src/streamer/civ7/present-batch.js',
    'compat': 'src/streamer/civ7/compat.js',
    'ring': 'src/streamer/shared/ring.js',
    'layout': 'src/renderer/civ7/layout.js',
    'av1Decoder': 'src/streamer/civ7/av1-decoder.js',
    'av1Backend': 'src/streamer/civ7/av1-decode.js',
    'av1Stream': 'src/streamer/session/av1-stream.js',
    'refresh': 'src/streamer/civ7/refresh-rate.js',
    'operationMode': 'src/streamer/civ7/operation-mode.js',
    'refreshRecord': 'src/streamer/civ7/refresh-rate-record.js',
    'compatTable': 'src/streamer/civ7/compat-functions.json',
}
STUBS = {
    'node:crypto': 'return {default:{createHash:function(){throw Error("Pipeline cache is disabled in the local experiment");}}};',
    'node:path': 'return {default:{join:function(){return Array.from(arguments).join("/");}}};',
    'node:fs/promises': 'return {default:{readFile:async function(path){var name=path.split("/").pop(),value=g.__moonlightNativeFiles&&g.__moonlightNativeFiles[name];if(value===undefined)throw Error("Missing local native record: "+name);return JSON.stringify(value);}}};',
    'node:timers/promises': 'return {setTimeout:function(ms){return new Promise(function(r){setTimeout(r,ms);});}};',
    'src/streamer/civ7/protocol.js': 'return {replyInteger:function(r,k){return BigInt(r[k]);},replyString:function(r,k){if(typeof r[k]!=="string")throw Error("Invalid reply string");return r[k];},replyArray:function(r,k){if(!Array.isArray(r[k]))throw Error("Invalid reply array");return r[k];}};',
    'src/streamer/civ7/decoder.js': 'return {create:function(options){return g.MoonlightNativeVideo.holdMovie(options.rpc.context);}};',
}

# The SDK owns shared native graphics modules; video/codec extensions stay here.
SHARED_SDK={'src/streamer/civ7/display.js': 'display', 'src/streamer/civ7/call-plan.js': 'callPlan', 'src/streamer/civ7/pipelines.js': 'pipelineHelpers', 'src/streamer/civ7/compat.js': 'compat', 'src/streamer/civ7/refresh-rate.js': 'refresh', 'src/streamer/civ7/refresh-rate-record.js': 'refreshRecord', 'src/streamer/civ7/compat-functions.json': 'compatTable', 'src/streamer/civ7/filesystem-functions.json': 'filesystemTable', 'src/streamer/shared/ring.js': 'ring'}


def build():
    manifest = json.loads((SOURCE / 'SOURCE.json').read_text())
    for name, expected in manifest['sha256'].items():
        if hashlib.sha256((SOURCE / name).read_bytes()).hexdigest() != expected:
            raise ValueError(f'Pinned native source changed: {name}')
    from civapps_native_ui import verify
    lock=verify(ROOT)
    for name,expected in manifest['sharedSDK']['sha256'].items():
        if lock['sharedNative'].get(name)!=expected:raise ValueError('SDK native dependency changed; requalify the streaming extension: '+name)
    factories = dict(STUBS)
    for name, field in SHARED_SDK.items():
        value='g.CivHomebrewSDK.graphicsModules.'+field
        factories[name]='return '+('{default:'+value+'}' if name.endswith('.json') else value)+';'


    from classic_modules import compile_graph
    factories=compile_graph(SOURCE,PUBLIC.values(),factories)
    shader_manifest = json.loads((SOURCE / 'src/renderer/civ7/prebuilt/renderer.json').read_text())
    blob = (SOURCE / 'src/renderer/civ7/prebuilt/shaders.bin').read_bytes()
    if hashlib.sha256(blob).hexdigest() != shader_manifest['blob']['sha256']:
        raise ValueError('Native shader blob checksum mismatch')
    regions = int.from_bytes(blob[16:20], 'little')
    entries = int.from_bytes(blob[20:24], 'little')
    shaders = {}
    for i in range(entries):
        at = 32 + regions * 16 + i * 80
        name = blob[at:at+24].split(b'\0')[0].decode('ascii')
        name = re.sub(r'-(\w)', lambda m: m[1].upper(), name)
        offset = int.from_bytes(blob[at+24:at+28], 'little')
        size = int.from_bytes(blob[at+28:at+32], 'little')
        data = blob[offset:offset+size]
        if len(data) != size or data[:4] != b'\x03\x02\x23\x07':
            raise ValueError(f'Invalid shader {name}')
        shaders[name] = data.hex()
    output = '/* Generated by tools/build-native-runtime.py. Moonlight-nx2 reference subset; see bundled notices. */\n(function(g){"use strict";\nconst Buffer=g.MoonlightNativeBuffer;\nconst __factories={\n'
    output += ',\n'.join(json.dumps(name) + ':function(){\n' + text + '\n}' for name, text in factories.items())
    output += '\n};const __cache={};function __require(name){if(!__cache[name]){if(!__factories[name])throw Error("Missing native module: "+name);__cache[name]=__factories[name]();}return __cache[name];}\n'
    output += 'const modules={' + ','.join(k + ':__require(' + json.dumps(v) + ')' + ('.default' if v.endswith('.json') else '') for k, v in PUBLIC.items()) + '};\n'
    output += 'modules.renderer={manifest:' + json.dumps(shader_manifest, separators=(',', ':')) + ',fingerprint:' + json.dumps(shader_manifest['blob']['sha256']) + ',shaders:{' + ','.join(k + ':Buffer.from(' + json.dumps(v) + ',"hex")' for k, v in shaders.items()) + '}};\n'
    output += 'g.MoonlightNativeModules=modules;\n})(typeof window!=="undefined"?window:globalThis);\n'
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(output)
    print(f'Native runtime: {OUT} ({len(output.encode()):,} bytes; {len(factories)} modules; no PC service)')


if __name__ == '__main__':
    build()
